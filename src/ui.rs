//! Embedded dashboard assets and the `apm ui` launcher.
//!
//! The dashboard is deliberately *not* a second service: `apm ui` binds the
//! same loopback REST server (`src/rest.rs`) and turns on three extra pieces:
//!
//! 1. static assets embedded at compile time (no Node at runtime, no file
//!    system access while serving);
//! 2. a process-local bearer token delivered in the URL fragment, so it never
//!    reaches the server, the HTML, a log file or browser storage;
//! 3. a strict CSP plus the existing Host/Origin/Bearer checks.
//!
//! Everything that mutates the ledger still goes through the REST handlers.

use std::io::Write;
use std::net::SocketAddr;
use std::path::PathBuf;
use std::time::Duration;

use crate::error::Result;
use crate::rest::{RestConfig, RestServer};

/// One embedded asset, generated by `build.rs`.
pub struct UiAsset {
    pub path: &'static str,
    pub bytes: &'static [u8],
    pub mime: &'static str,
}

include!(concat!(env!("OUT_DIR"), "/ui_assets.rs"));

/// The CSP used for every UI response. `'self'` only: the bundle has no inline
/// scripts or styles, no remote fonts, and fetches the same-origin API.
pub const CSP: &str = "default-src 'none'; script-src 'self'; style-src 'self'; \
     img-src 'self' data:; connect-src 'self'; base-uri 'none'; form-action 'none'; \
     frame-ancestors 'none'; object-src 'none'";

/// Look up an embedded asset by its bundle-relative path (`assets/app.js`).
pub fn find(path: &str) -> Option<&'static UiAsset> {
    UI_ASSETS.iter().find(|asset| asset.path == path)
}

pub fn index() -> &'static UiAsset {
    find("index.html").expect("build.rs guarantees an index.html")
}

/// A fresh bearer token for this process only. Never persisted and never
/// printed: the browser receives it by exchanging the bootstrap ticket.
pub fn process_token() -> String {
    format!("apm_ui_{}", uuid::Uuid::new_v4().simple())
}

/// A one-time, short-lived startup credential. Safe to put in the printed URL:
/// it dies on first use (or after the TTL) and cannot call the API by itself.
pub fn bootstrap_ticket() -> String {
    format!("apm_boot_{}", uuid::Uuid::new_v4().simple())
}

/// The URL handed to the browser. Only the single-use ticket travels in the
/// fragment; the browser exchanges it for the real token over `POST
/// /api/bootstrap` and strips the fragment immediately.
pub fn launch_url(addr: SocketAddr, ticket: &str) -> String {
    format!("http://{addr}/ui/#ticket={ticket}")
}

/// Everything `apm ui` needs from the CLI.
#[derive(Debug, Clone)]
pub struct UiOptions {
    pub db: PathBuf,
    pub project: Option<String>,
    pub agent: String,
    pub listen: String,
    pub allow_remote: bool,
    pub session: Option<String>,
    pub run: Option<String>,
    pub now: Option<i64>,
    pub timeout: Duration,
    /// How long the browser has to exchange its one-time ticket.
    pub ticket_ttl: Duration,
    /// Open the default browser (default). `--no-open` clears it.
    pub open: bool,
}

/// Bind, announce, open the browser and serve until the process is stopped.
pub fn serve(options: UiOptions) -> Result<()> {
    // The real token stays in this process; only the ticket is printed.
    let token = process_token();
    let ticket = bootstrap_ticket();
    let config = RestConfig {
        db: options.db,
        project: options.project,
        agent: options.agent,
        listen: options.listen,
        allow_remote: options.allow_remote,
        session: options.session,
        run: options.run,
        token: token.clone(),
        read_timeout: options.timeout,
        now: options.now,
        ui: true,
        bootstrap_ticket: Some(ticket.clone()),
        bootstrap_ttl: options.ticket_ttl,
    };
    let server = RestServer::bind(config)?;
    let addr = server.local_addr()?;
    let url = launch_url(addr, &ticket);

    println!(
        "apm ui listening on http://{addr} (loopback: {}, assets: {UI_SOURCE})",
        addr.ip().is_loopback()
    );
    // Only the one-time ticket appears here. The bearer token is never printed
    // (the reviewer regression: `ui: …#token=` landed in CI logs).
    println!("ui: {url}");
    println!("listening on {addr}");
    if !addr.ip().is_loopback() {
        eprintln!(
            "apm ui: WARNING: bound to {} (--allow-remote). The dashboard is reachable \
             from the network; the bearer token is the only protection.",
            addr.ip()
        );
    }
    let _ = std::io::stdout().flush();

    if options.open && !open_browser(&url) {
        eprintln!("apm ui: could not launch a browser; open the URL printed above");
    }
    server.serve()
}

/// Open `url` with the platform handler. Returns false when no handler could be
/// spawned; the caller only warns, because the URL is already printed.
fn open_browser(url: &str) -> bool {
    // Test seam: point this at a script to observe the launch without a display.
    if let Ok(command) = std::env::var("APM_UI_OPEN_CMD") {
        if command.trim().is_empty() {
            return false;
        }
        return spawn_opener(&mut std::process::Command::new(command), url);
    }
    if cfg!(target_os = "macos") {
        spawn_opener(&mut std::process::Command::new("open"), url)
    } else if cfg!(target_os = "windows") {
        let mut command = std::process::Command::new("cmd");
        command.args(["/C", "start", ""]);
        spawn_opener(&mut command, url)
    } else {
        let mut command = std::process::Command::new("xdg-open");
        spawn_opener(&mut command, url)
    }
}

fn spawn_opener(command: &mut std::process::Command, url: &str) -> bool {
    use std::process::Stdio;
    command
        .arg(url)
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .spawn()
        .is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn embedded_assets_always_have_an_index() {
        assert!(find("index.html").is_some());
        assert_eq!(index().mime, "text/html; charset=utf-8");
        assert!(!index().bytes.is_empty());
    }

    #[test]
    fn token_and_ticket_are_process_local_and_distinct() {
        let token = process_token();
        let ticket = bootstrap_ticket();
        assert!(token.starts_with("apm_ui_"));
        assert!(ticket.starts_with("apm_boot_"));
        assert_ne!(token, ticket);
        assert_ne!(process_token(), token);
        assert!(!token.contains('/') && !ticket.contains('/'));
    }

    #[test]
    fn launch_url_carries_only_the_one_time_ticket() {
        let addr: SocketAddr = "127.0.0.1:7717".parse().unwrap();
        let url = launch_url(addr, "apm_boot_abc");
        assert_eq!(url, "http://127.0.0.1:7717/ui/#ticket=apm_boot_abc");
        assert!(!url.contains("apm_ui_"));
    }
}
