//! Embed the dashboard assets into the binary.
//!
//! `ui/dist` (produced by `npm run ui:build`, committed to git) is the real
//! source. When it is missing — a fresh checkout without a frontend build, or
//! an early CI run — we fall back to `src/ui_fallback/`, a tiny page that still
//! exercises the fragment-token flow, so `cargo build` never requires Node.
//!
//! The generated table is data only: `src/ui.rs` adds lookup and policy.

use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    println!("cargo:rerun-if-changed=ui/dist");
    println!("cargo:rerun-if-changed=src/ui_fallback");

    let dist = Path::new("ui/dist");
    let (root, source) = if dist.join("index.html").is_file() {
        (dist, "dist")
    } else {
        (Path::new("src/ui_fallback"), "fallback")
    };

    let mut files = Vec::new();
    collect(root, root, &mut files);
    files.sort();
    if !files.iter().any(|relative| relative == "index.html") {
        panic!(
            "{} has no index.html; the UI needs an entry document",
            root.display()
        );
    }

    let mut generated = String::new();
    generated.push_str("// @generated by build.rs — do not edit.\n");
    generated.push_str(&format!("pub const UI_SOURCE: &str = {:?};\n", source));
    generated.push_str("pub static UI_ASSETS: &[UiAsset] = &[\n");
    for relative in &files {
        let absolute = fs::canonicalize(root.join(relative))
            .unwrap_or_else(|e| panic!("cannot canonicalize {relative}: {e}"));
        let absolute = absolute.to_string_lossy();
        generated.push_str(&format!(
            "    UiAsset {{ path: {:?}, bytes: include_bytes!({:?}), mime: {:?} }},\n",
            relative,
            absolute,
            mime_for(relative)
        ));
    }
    generated.push_str("];\n");

    let out = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("ui_assets.rs");
    fs::write(&out, generated).expect("write ui_assets.rs");
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<String>) {
    let entries = match fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(e) => panic!("cannot read {}: {e}", dir.display()),
    };
    for entry in entries {
        let entry = entry.unwrap_or_else(|e| panic!("cannot read dir entry: {e}"));
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, out);
            continue;
        }
        // Dotfiles and editor droppings are not part of the bundle.
        let name = path
            .file_name()
            .map(|n| n.to_string_lossy().to_string())
            .unwrap_or_default();
        if name.starts_with('.') {
            continue;
        }
        let relative = path
            .strip_prefix(root)
            .expect("walked path is under root")
            .to_string_lossy()
            .replace('\\', "/");
        out.push(relative);
    }
}

fn mime_for(path: &str) -> &'static str {
    let ext = path.rsplit_once('.').map(|(_, ext)| ext).unwrap_or("");
    match ext {
        "html" => "text/html; charset=utf-8",
        "js" | "mjs" => "text/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "json" | "map" => "application/json; charset=utf-8",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "jpg" | "jpeg" => "image/jpeg",
        "webp" => "image/webp",
        "ico" => "image/x-icon",
        "woff2" => "font/woff2",
        "woff" => "font/woff",
        "txt" => "text/plain; charset=utf-8",
        "wasm" => "application/wasm",
        _ => "application/octet-stream",
    }
}
